#!/usr/bin/env bash
set -euo pipefail

URL=${L1_DATA_TEST_PG:-postgres://l1data:l1data@localhost:5433/shop}
OUT=$(dirname "$0")/../crates/engine/src/sql/keywords.rs

list() {
  psql "$URL" -At -c "select string_agg('    \"' || word || '\",', E'\n' order by word) from pg_get_keywords() where catcode in ($1)"
}

{
  echo "//! PostgreSQL 16's keywords, from \`pg_get_keywords()\`. Generated by dev/pg-keywords.sh; the"
  echo "//! pg-test \`the_keyword_lists_match_the_server\` fails when they drift."
  echo
  echo "/// Reserved and column-name keywords: never a function name, so \`name(\` is syntax."
  echo "pub(crate) const NEVER_A_FUNCTION: &[&str] = &["
  list "'R', 'C'"
  echo "];"
  echo
  echo "/// Type-or-function-name and unreserved keywords: usable as function names and as aliases."
  echo "pub(crate) const OTHER_KEYWORDS: &[&str] = &["
  list "'T', 'U'"
  echo "];"
  echo
  echo "/// Reserved keywords: never a column name or a function name."
  echo "pub(crate) const RESERVED: &[&str] = &["
  list "'R'"
  echo "];"
  echo
  echo '/// Type-or-function-name keywords: never a column name, but `left(` can be a call.'
  echo "pub(crate) const TYPE_OR_FUNCTION_NAME: &[&str] = &["
  list "'T'"
  echo "];"
} >"$OUT"
echo "wrote $OUT"
